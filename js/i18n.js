function getTranslation(key) {
  if (translations[currentLanguage] && translations[currentLanguage][key]) {
    return translations[currentLanguage][key];
  }
  if (translations['en'][key]) {
    return translations['en'][key];
  }
  return key;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  localStorage.setItem('hsm_language', lang);

  // Update elements with data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    const txt = getTranslation(key);
    if (txt) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) {
          el.setAttribute('placeholder', txt);
        }
      } else {
        el.textContent = txt;
      }
    }
  });

  // Update active status on language selector buttons/options
  document.querySelectorAll('.lang-option').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Trigger language change event for dynamic scripts
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: currentLanguage } }));
}

function initI18n() {
  setLanguage(currentLanguage);
}

// Global expose
window.i18n = {
  t: getTranslation,
  setLanguage: setLanguage,
  getCurrentLang: () => currentLanguage,
  init: initI18n
};

document.addEventListener('DOMContentLoaded', () => {
  initI18n();
});
